import {assessPublishedTask} from './helpers/task-score.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import sharp from 'sharp';

test('上传背景、文件权限、公开编辑与移除恢复、交付退回重提和最终验收',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'momoyu-delivery-'));
  const child=spawn(process.execPath,['server/index.mjs'],{windowsHide:true,env:{...process.env,HOST:'127.0.0.1',PORT:'0',DATA_DIR:dir,DIFY_API_KEY:''},stdio:['ignore','pipe','pipe']});
  t.after(async()=>{child.kill();if(child.exitCode===null)await once(child,'exit');rmSync(dir,{recursive:true,force:true});});
  let output='',base;for await(const c of child.stdout){output+=c;const m=output.match(/"port":(\d+)/);if(m){base='http://127.0.0.1:'+m[1];break;}}
  const call=async(path,method='GET',body,cookie)=>fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',...cookie?{cookie}:{}},body:body===undefined?undefined:JSON.stringify(body)});
  const json=async(path,method,body,cookie,expected=200)=>{const r=await call(path,method,body,cookie);const d=await r.json();assert.equal(r.status,expected,JSON.stringify(d));return d;};
  const register=async username=>{const r=await call('/auth/register','POST',{username,password:'TestUpload2026',displayName:username,department:'验收'});assert.equal(r.status,201);return r.headers.get('set-cookie').split(';')[0];};
  const a=await register('alice'),b=await register('bob'),e=await register('eve');
  const id=(await json('/requests','POST',{},a,201)).request.id;
  const upload=async(name,bytes,cookie=a,requestId=id,expected=201)=>{const form=new FormData();form.append('file',new Blob([bytes]),name);const r=await fetch(base+'/api/requests/'+requestId+'/attachments',{method:'POST',headers:{cookie},body:form});const data=await r.json();assert.equal(r.status,expected,JSON.stringify(data));return data;};
  const original='工号,姓名\n001,示例员工\n';
  const csv=(await upload('核对原表.csv',original)).attachment;
  const sourceImage=await sharp({create:{width:160,height:80,channels:3,background:'#f07a29'}}).jpeg().withExif({IFD0:{Artist:'private-fixture'}}).toBuffer();
  const photo=(await upload('我的背景.jpg',sourceImage)).attachment;assert.equal(photo.included,false);
  await upload('test.html','<script/>',a,id,415);await upload('fake.png','bad',a,id,415);
  await upload('too-large.zip',Buffer.alloc(50*1024*1024+1),a,id,413);
  const extraId=(await json('/requests','POST',{},a,201)).request.id;
  const other=(await upload('别的卡片.png',await sharp({create:{width:8,height:8,channels:3,background:'#fff'}}).png().toBuffer(),a,extraId)).attachment;
  await json(`/requests/${id}/cover`,'POST',{attachmentId:other.id},a,400);
  await json(`/requests/${id}/cover`,'POST',{attachmentId:photo.id},a);
  await json(`/requests/${id}`,'PATCH',{title:'附件协作验收',problem:'需要核对原表',desiredOutcome:'列出漏项',deliverables:['差异清单'],anonymous:true},a);
  assert.equal((await call(`/requests/${id}/cover`,'GET',undefined,b)).status,404);
  await json(`/requests/${id}/publish`,'POST',{confirmed:true},a);
  const publicCard=(await json(`/requests/${id}`,'GET',undefined,e)).request;assert.equal(publicCard.materialFiles.length,0);assert.equal(publicCard.materialFileCount,1);assert.equal(publicCard.owner,null);
  const preview=await call(`/requests/${id}/cover`);assert.equal(preview.headers.get('content-type'),'image/webp');const metadata=await sharp(Buffer.from(await preview.arrayBuffer())).metadata();assert.equal(metadata.exif,undefined);
  await json(`/requests/${id}`,'PATCH',{title:'新版标题'},a,400);
  await json(`/requests/${id}`,'PATCH',{title:'新版标题',confirmed:true},a);
  await json(`/requests/${id}`,'PATCH',{deliverables:[],acceptanceCriteria:[],confirmed:true},a,400);
  await json(`/requests/${id}/archive`,'POST',{confirmed:true},e,404);
  await json(`/requests/${id}/archive`,'POST',{confirmed:true},a);
  assert.equal((await call(`/requests/${id}`,'GET',undefined,e)).status,404);assert.equal((await call(`/requests/${id}/cover`)).status,404);
  assert.equal((await json('/me/requests','GET',undefined,a)).archived.length,1);
  await json(`/requests/${id}/restore`,'POST',{confirmed:true},a);
  assert.equal((await call('/attachments/'+csv.id,'GET',undefined,b)).status,404);
  assessPublishedTask(dir,id);
  await json(`/requests/${id}/claim`,'POST',{},b);
  assert.equal(await(await call('/attachments/'+csv.id,'GET',undefined,b)).text(),original);
  assert.equal((await call('/attachments/'+photo.id,'GET',undefined,b)).status,404);
  assert.equal((await call('/attachments/'+csv.id,'GET',undefined,e)).status,404);
  await json(`/requests/${id}`,'PATCH',{title:'接取后不能改原需求',confirmed:true},a,409);
  await json(`/requests/${id}/archive`,'POST',{confirmed:true},a,409);
  await json(`/requests/${id}/workspace`,'GET',undefined,e,404);
  const supplement=(await upload('补充现场图片.jpg',sourceImage,a)).attachment;assert.equal(supplement.included,true);assert.equal((await call('/attachments/'+supplement.id,'GET',undefined,b)).status,200);
  const out1=(await upload('成果v1.csv','工号,漏项\n001,是',b)).attachment;
  assert.equal((await call('/attachments/'+out1.id,'GET',undefined,a)).status,404);
  await json(`/requests/${id}/submit`,'POST',{note:'第一版',attachmentIds:[csv.id]},b,400);
  const first=await json(`/requests/${id}/submit`,'POST',{note:'第一版',attachmentIds:[out1.id]},b);assert.equal(first.request.status,'submitted');
  assert.equal((await call('/attachments/'+out1.id,'GET',undefined,a)).status,200);
  await json(`/requests/${id}/submit`,'POST',{note:'重复提交',attachmentIds:[]},b,409);
  await json(`/requests/${id}/review`,'POST',{submissionId:first.submissions[0].id,decision:'changes_requested',feedback:''},a,400);
  await json(`/requests/${id}/review`,'POST',{submissionId:first.submissions[0].id,decision:'changes_requested',feedback:'请补充漏项总数'},a);
  const out2=(await upload('成果v2.csv','工号,漏项\n001,是\n总数,1',b)).attachment;
  const second=await json(`/requests/${id}/submit`,'POST',{note:'已补总数',attachmentIds:[out2.id]},b);assert.equal(second.submissions.length,2);assert.equal(second.submissions[0].version,2);assert.equal(second.submissions[1].feedback,'请补充漏项总数');
  await json(`/requests/${id}/review`,'POST',{submissionId:first.submissions[0].id,decision:'approve',feedback:'',confirmed:true},a,409);
  const completed=await json(`/requests/${id}/review`,'POST',{submissionId:second.submissions[0].id,decision:'approve',feedback:'验收通过',confirmed:true},a);assert.equal(completed.request.status,'completed');
  assert.equal((await call('/attachments/'+out1.id,'GET',undefined,a)).status,200);assert.equal((await call('/attachments/'+out2.id,'GET',undefined,e)).status,404);
  await upload('finished.txt','late',b,id,409);
  await json(`/requests/${extraId}/attachments/${other.id}`,'DELETE',undefined,a);
  assert.equal((await call('/attachments/'+other.id,'GET',undefined,a)).status,404);
  const manyId=(await json('/requests','POST',{},a,201)).request.id;
  for(let i=0;i<100;i++)await upload('分批材料'+i+'.txt','small fixture',a,manyId);
  await upload('第101个.txt','over limit',a,manyId,413);
});
